import os, sys, tempfile, re
tmp = tempfile.mkdtemp()
os.environ.update(MESHPI_DB=os.path.join(tmp, "messages.db"), MESHPI_PASSWORD="test-password-123", MESHPI_USER="admin")
sys.path.insert(0, sys.argv[1])
import app as m

c = m.app.test_client()
ok = True
def check(name, cond, extra=""):
    global ok
    ok &= bool(cond)
    print("ok  " if cond else "FAIL", name, extra)

r = c.get("/")
check("/ without session -> redirect to /login", r.status_code == 302 and r.headers["Location"].startswith("/login"), r.headers.get("Location"))
check("no browser Basic-auth popup header", "WWW-Authenticate" not in r.headers)
r = c.get("/login")
check("login page renders", r.status_code == 200 and b'name="password"' in r.data)
check("static files reachable before login", c.get("/static/style.css").status_code == 200)
r = c.get("/api/status")
check("/api without session -> JSON 401", r.status_code == 401 and r.is_json, r.get_data(as_text=True)[:60])
r = c.post("/login", data={"user": "admin", "password": "wrong"})
check("wrong password -> 401 + message", r.status_code == 401 and "Невірний".encode() in r.data)
r = c.post("/login", data={"user": "admin", "password": "test-password-123", "next": "//evil.example"})
check("login ok, open-redirect blocked", r.status_code == 302 and r.headers["Location"] == "/", r.headers.get("Location"))
cookie = r.headers.get("Set-Cookie", "")
check("cookie is HttpOnly + SameSite", "HttpOnly" in cookie and "SameSite=Lax" in cookie, cookie.split(";")[0][:30])
r = c.get("/")
check("/ with session -> app page", r.status_code == 200 and b'id="tabbar"' in r.data)
html = r.get_data(as_text=True)
tabs = re.findall(r'<div class="tabpane" data-tab="(\w+)"', html)
check("seven tab panes", tabs == ["overview", "messages", "nodes", "mesh", "radio", "node", "system"], str(tabs))
check("two isolated scripts", html.count("(function () {") == 2)
check("/settings redirects to a tab", c.get("/settings").headers["Location"] == "/#node")
r = c.post("/logout")
check("logout -> /login", r.status_code == 302 and r.headers["Location"] == "/login")
check("after logout / redirects again", c.get("/").status_code == 302)
r = c.get("/", headers={"Authorization": "Basic YWRtaW46dGVzdC1wYXNzd29yZC0xMjM="})
check("Basic auth still works for scripts", r.status_code == 200)
c2 = m.app.test_client()
c2.post("/login", data={"user": "admin", "password": "test-password-123"})
check("session persists across requests", c2.get("/").status_code == 200)
r = c2.get("/login")
check("logged-in user visiting /login is sent on", r.status_code in (200, 302))
sys.exit(0 if ok else 1)
